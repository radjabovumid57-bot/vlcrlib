#!/usr/bin/env python3
"""Generate the repetitive parts of the language bindings.

`bindings/ffi/vlcr_ffi.h` is the single source of truth for the binding ABI.
This script parses it and emits:

  * bindings/python/vlcrlib/_native.py     ctypes signatures
  * bindings/csharp/Vlcrlib/NativeMethods.g.cs   P/Invoke declarations
  * bindings/java/src/main/java/org/vlcrlib/Native.java   native declarations
  * bindings/java/native/vlcr_jni.c        JNI glue

The idiomatic wrappers around these (Window, Shapes, Text, ...) are written by
hand in each language. Run this after adding a function to vlcr_ffi.h:

    python bindings/tools/gen_bindings.py

No third-party dependencies, Python 3.9+.
"""

from __future__ import annotations

import pathlib
import re
import sys
from dataclasses import dataclass

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = ROOT / "bindings" / "ffi" / "vlcr_ffi.h"
SCANCODES = ROOT / "external" / "SDL3" / "include" / "SDL3" / "SDL_scancode.h"

BANNER = "Generated by bindings/tools/gen_bindings.py from bindings/ffi/vlcr_ffi.h — do not edit."


# --------------------------------------------------------------------------
# C type model
# --------------------------------------------------------------------------
# kind: void | i32 | u32 | f32 | f64 | str | out_f32 | out_i32 | ptr
TYPE_MAP = {
    "void": "void",
    "int": "i32",
    "int32_t": "i32",
    "vlcr_handle": "i32",
    "uint32_t": "u32",
    "unsignedint": "u32",
    "float": "f32",
    "double": "f64",
    "void*": "ptr",
    "constchar*": "str",
    "float*": "out_f32",
    "int*": "out_i32",
}

PY_CTYPES = {
    "i32": "c_int",
    "u32": "c_uint32",
    "f32": "c_float",
    "f64": "c_double",
    "str": "c_char_p",
    "ptr": "c_void_p",
    "out_f32": "POINTER(c_float)",
    "out_i32": "POINTER(c_int)",
}

CS_TYPE = {
    "i32": "int",
    "u32": "uint",
    "f32": "float",
    "f64": "double",
    "str": "string",
    "ptr": "IntPtr",
    "out_f32": "out float",
    "out_i32": "out int",
}

JAVA_TYPE = {
    "i32": "int",
    "u32": "int",
    "f32": "float",
    "f64": "double",
    "str": "String",
    "ptr": "long",
    "out_f32": "float[]",
    "out_i32": "int[]",
}

JNI_TYPE = {
    "i32": "jint",
    "u32": "jint",
    "f32": "jfloat",
    "f64": "jdouble",
    "str": "jstring",
    "ptr": "jlong",
    "out_f32": "jfloatArray",
    "out_i32": "jintArray",
}


@dataclass
class Param:
    name: str
    ctype: str
    kind: str

    @property
    def is_out(self) -> bool:
        return self.kind.startswith("out_")


@dataclass
class Function:
    name: str
    ctype: str
    kind: str
    params: list

    @property
    def method(self) -> str:
        """C name without the vlcr_ prefix, camelCased (Java/C# style)."""
        stem = self.name[len("vlcr_"):] if self.name.startswith("vlcr_") else self.name
        parts = stem.split("_")
        return parts[0] + "".join(_cap(p) for p in parts[1:])


def _cap(part: str) -> str:
    """Capitalise a name segment, keeping digit-first segments readable: 2d -> 2D."""
    if not part:
        return part
    if part[0].isdigit():
        return part[0] + part[1:].capitalize()
    return part[0].upper() + part[1:].lower()


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def split_type(decl: str) -> tuple:
    """'const char *title' -> ('const char *', 'title')."""
    m = re.match(r"^(.*?)([A-Za-z_]\w*)\s*$", decl.strip())
    if not m:
        raise ValueError(f"cannot parse declaration: {decl!r}")
    return m.group(1), m.group(2)


def classify(ctype: str) -> str:
    norm = re.sub(r"\s+", "", ctype)
    if norm not in TYPE_MAP:
        raise ValueError(f"unhandled C type: {ctype!r}")
    return TYPE_MAP[norm]


def parse_header() -> list:
    text = strip_comments(HEADER.read_text(encoding="utf-8"))
    functions = []

    # Declarations start at the beginning of a line with VLCR_FFI_API; the
    # macro-definition block in the header does not, so it is skipped.
    for match in re.finditer(r"^[ \t]*VLCR_FFI_API\b([^;]*);", text, re.M):
        decl = match.group(1)
        if "(" not in decl:
            continue
        head, tail = decl.split("(", 1)
        params_text = tail.rsplit(")", 1)[0]
        ctype, name = split_type(head)

        params = []
        if params_text.strip() and params_text.strip() != "void":
            for raw in params_text.split(","):
                ptype, pname = split_type(raw)
                params.append(Param(pname, ptype.strip(), classify(ptype)))

        functions.append(Function(name, ctype.strip(), classify(ctype), params))

    return functions


# --------------------------------------------------------------------------
# Python
# --------------------------------------------------------------------------
def gen_python(functions: list) -> str:
    lines = [
        f'"""{BANNER}"""',
        "",
        "from ctypes import (POINTER, c_char_p, c_double, c_float, c_int,",
        "                    c_uint32, c_void_p)",
        "",
        "",
        "def declare(lib):",
        '    """Attach restype/argtypes to a ctypes CDLL holding the native library."""',
    ]
    for fn in functions:
        args = ", ".join(PY_CTYPES[p.kind] for p in fn.params)
        lines.append(f"    sig = lib.{fn.name}")
        lines.append(f"    sig.restype = {PY_CTYPES.get(fn.kind, 'None')}")
        lines.append(f"    sig.argtypes = [{args}]")
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------
# C#
# --------------------------------------------------------------------------
def gen_csharp(functions: list) -> str:
    lines = [
        "// " + BANNER,
        "using System;",
        "using System.Runtime.InteropServices;",
        "",
        "namespace Vlcrlib",
        "{",
        "    internal static partial class Native",
        "    {",
        '        internal const string Lib = "vlcr_ffi";',
        "",
    ]
    for fn in functions:
        # String returns are marshalled by hand: .NET's LPUTF8Str return
        # marshalling corrupts the heap on a `const char *` that points into
        # the native module (it is not CoTaskMem-allocated).
        ret = "IntPtr" if fn.kind == "str" else CS_TYPE.get(fn.kind, "void")
        params = []
        for p in fn.params:
            cs = CS_TYPE[p.kind]
            if p.kind == "str":
                params.append(f'[MarshalAs(UnmanagedType.LPUTF8Str)] string {p.name}')
            else:
                params.append(f"{cs} {p.name}")
        lines.append("        [DllImport(Lib, CallingConvention = CallingConvention.Cdecl,")
        lines.append(f'            EntryPoint = "{fn.name}")]')
        lines.append(f"        internal static extern {ret} {fn.method}({', '.join(params)});")
        lines.append("")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Java
# --------------------------------------------------------------------------
def gen_java(functions: list) -> str:
    lines = [
        "// " + BANNER,
        "package org.vlcrlib;",
        "",
        "final class Native",
        "{",
        "    private Native() {}",
        "",
    ]
    for fn in functions:
        ret = JAVA_TYPE.get(fn.kind, "void")
        params = ", ".join(f"{JAVA_TYPE[p.kind]} {p.name}" for p in fn.params)
        lines.append(f"    static native {ret} {fn.method}({params});")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def jni_symbol(fn: Function) -> str:
    # JNI name mangling: '_' -> '_1', '/' and '.' already encoded in class path.
    return "Java_org_vlcrlib_Native_" + fn.method.replace("_", "_1")


def gen_jni_c(functions: list) -> str:
    lines = [
        "/* " + BANNER + " */",
        "",
        "#include <jni.h>",
        "#include <stdint.h>",
        "#include <stdlib.h>",
        "",
        "#include \"org_vlcrlib_Native.h\"",
        "#include \"vlcr_ffi.h\"",
        "",
    ]
    for fn in functions:
        jret = JNI_TYPE.get(fn.kind, "void")
        params = ", ".join(f"{JNI_TYPE[p.kind]} {p.name}" for p in fn.params)
        lines.append(f"JNIEXPORT {jret} JNICALL {jni_symbol(fn)}(JNIEnv *env, jclass cls"
                     + (", " + params if params else "") + ")")
        lines.append("{")
        lines.append("    (void)cls;")

        call_args = []
        cleanup = []
        for p in fn.params:
            if p.kind == "str":
                lines.append(f"    const char *c_{p.name} = {p.name} ? (*env)->GetStringUTFChars(env, {p.name}, NULL) : NULL;")
                call_args.append(f"c_{p.name}")
                cleanup.append(f"    if (c_{p.name}) (*env)->ReleaseStringUTFChars(env, {p.name}, c_{p.name});")
            elif p.kind == "ptr":
                call_args.append(f"(void *)(intptr_t){p.name}")
            elif p.is_out:
                base = "float" if p.kind == "out_f32" else "int"
                lines.append(f"    {base} local_{p.name} = 0;")
                call_args.append(f"&local_{p.name}")
            else:
                call_args.append(f"({p.ctype}){p.name}".replace("  ", " "))

        call = f"{fn.name}({', '.join(call_args)})"

        if fn.kind == "void":
            lines.append(f"    {call};")
        elif fn.kind == "str":
            lines.append(f"    const char *result = {call};")
            lines.append("    jstring out = result ? (*env)->NewStringUTF(env, result) : NULL;")
        elif fn.kind in ("i32", "u32"):
            lines.append(f"    jint result = (jint){call};")
        elif fn.kind == "f32":
            lines.append(f"    jfloat result = (jfloat){call};")
        elif fn.kind == "f64":
            lines.append(f"    jdouble result = (jdouble){call};")
        elif fn.kind == "ptr":
            lines.append(f"    jlong result = (jlong)(intptr_t){call};")

        # Copy the out-parameters back into the Java arrays after the call.
        for p in fn.params:
            if p.is_out:
                base = "Float" if p.kind == "out_f32" else "Int"
                lines.append(f"    if ({p.name} && (*env)->GetArrayLength(env, {p.name}) >= 1) {{")
                lines.append(f"        (*env)->Set{base}ArrayRegion(env, {p.name}, 0, 1, &local_{p.name});")
                lines.append("    }")

        for line in cleanup:
            lines.append(line)

        if fn.kind == "void":
            lines.append("    return;")
        elif fn.kind == "str":
            lines.append("    return out;")
        else:
            lines.append("    return result;")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Keyboard constants (the engine's IsKey*() take SDL scancodes)
# --------------------------------------------------------------------------
def key_entries() -> list:
    """[(name, value)] for every SDL_SCANCODE_* constant, name PascalCased."""
    if not SCANCODES.exists():
        return []

    text = strip_comments(SCANCODES.read_text(encoding="utf-8", errors="replace"))
    entries = []
    seen = set()
    for raw, value in re.findall(r"SDL_SCANCODE_([A-Z0-9_]+)\s*=\s*(\d+)", text):
        parts = raw.split("_")
        name = "".join(_cap(p) for p in parts)
        if name[0].isdigit():
            name = "Num" + name
        # Constant names must not shadow Object members in C# / Java.
        if name in ("Equals", "GetHashCode", "GetType", "ToString", "Clone"):
            name += "Key"
        if name in seen:
            continue
        seen.add(name)
        entries.append((name, int(value)))
    return entries


def gen_python_keys(entries: list) -> str:
    lines = [
        f'"""{BANNER} Keyboard scancodes accepted by Window.key_down() and friends."""',
        "",
        "from enum import IntEnum",
        "",
        "",
        "class Key(IntEnum):",
        '    """SDL3 scancodes; the names mirror SDL_SCANCODE_* (A, Num1, ...)."""',
        "",
    ]
    lines += [f"    {name} = {value}" for name, value in entries]
    lines.append("")
    return "\n".join(lines)


def gen_csharp_keys(entries: list) -> str:
    lines = [
        "// " + BANNER,
        "",
        "namespace Vlcrlib",
        "{",
        "    /// <summary>SDL3 scancodes; names mirror SDL_SCANCODE_* (A, Num1, ...).</summary>",
        "    public static class Keys",
        "    {",
    ]
    lines += [f"        public const int {name} = {value};" for name, value in entries]
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_java_keys(entries: list) -> str:
    lines = [
        "// " + BANNER,
        "package org.vlcrlib;",
        "",
        "/** SDL3 scancodes; names mirror SDL_SCANCODE_* (A, Num1, ...). */",
        "public final class Key",
        "{",
        "    private Key() {}",
        "",
    ]
    lines += [f"    public static final int {name} = {value};" for name, value in entries]
    lines += ["}", ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------
def write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"  wrote {path.relative_to(ROOT)}")


def main() -> int:
    functions = parse_header()
    if not functions:
        print("error: no functions found in vlcr_ffi.h", file=sys.stderr)
        return 1

    keys = key_entries()
    if not keys:
        print(f"warning: {SCANCODES} not found; key tables not regenerated", file=sys.stderr)

    write(ROOT / "bindings/python/vlcrlib/_native.py", gen_python(functions))
    write(ROOT / "bindings/csharp/Vlcrlib/NativeMethods.g.cs", gen_csharp(functions))
    write(ROOT / "bindings/java/src/main/java/org/vlcrlib/Native.java", gen_java(functions))
    write(ROOT / "bindings/java/native/vlcr_jni.c", gen_jni_c(functions))

    if keys:
        write(ROOT / "bindings/python/vlcrlib/keys.py", gen_python_keys(keys))
        write(ROOT / "bindings/csharp/Vlcrlib/Keys.g.cs", gen_csharp_keys(keys))
        write(ROOT / "bindings/java/src/main/java/org/vlcrlib/Key.java", gen_java_keys(keys))

    print(f"generated bindings for {len(functions)} functions, {len(keys)} keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
